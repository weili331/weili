function analyzeBatch(items) {
  return items.map(item => {
    const analysis = analyzeItem(item);
    return { ...item, legalAnalysis: analysis };
  });
}

function analyzeItem(item) {
  const text = `${item.title} ${item.summary || ''}`;

  for (const [pattern, info] of Object.entries(LEGAL_KEYWORDS)) {
    if (pattern.split('|').some(p => text.includes(p))) {
      return info;
    }
  }

  // 默认分析
  return {
    law: '《民法典》',
    analysis: '该事件涉及民事法律关系，应根据具体事实和法律规定进行分析。建议关注相关法律法规的适用，注意保留证据、依法维权。',
  };
}

module.exports = { analyzeBatch, analyzeItem };
